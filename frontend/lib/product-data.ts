/* ── Shared product catalogue data ─────────────────────────────────── */

export interface ProductCategory {
  id: number;
  name: string;
  slug: string;
  parentId: number | null;
  iconType: 'lucide' | 'upload' | null;
  iconName: string | null;
  iconUrl: string | null;
  description: string;
  productCount: number;
}

export interface ProductBrand {
  id: number;
  name: string;
  slug: string;
  logoType: 'lucide' | 'upload' | null;
  logoName: string | null;
  logoUrl: string | null;
  categoryId: number | null;
  subCategoryId: number | null;
  website: string;
  description: string;
  featured: boolean;
  productCount: number;
}

function c(
  id: number, name: string, slug: string,
  parentId: number | null,
  iconName: string | null = null,
): ProductCategory {
  return {
    id, name, slug, parentId,
    iconType: iconName ? 'lucide' : null,
    iconName, iconUrl: null, description: '', productCount: 0,
  };
}

function b(
  id: number, name: string, slug: string,
  categoryId: number | null, subCategoryId: number | null = null,
  featured = false,
): ProductBrand {
  return {
    id, name, slug,
    logoType: null, logoName: null, logoUrl: null,
    categoryId, subCategoryId,
    website: '', description: '', featured, productCount: 0,
  };
}

